export type SpiceLevel =
  | 'Not Spicy'
  | 'Mild'
  | 'Low to Medium'
  | 'Medium'
  | 'Spicy'
  | 'Extra Spicy'
  | 'Very Spicy'
  | 'Customizable';

export interface MenuItem {
  id: string;
  name: string;
  category: MenuCategory;
  description: string;
  image: string | null;
  spiceLevel: SpiceLevel;
  spiceHeatValue: number; // 0 (Not Spicy) to 5 (Extra Spicy) for filtering/display
  portionSize?: string;
  customerPrice: number | null; // Customer-facing price in PKR. NULL if unconfirmed.
  customerPriceLarge?: number | null; // Optional Large size price if applicable.
  supplierReferencePrice?: number | null; // STRICTLY INTERNAL - never expose to public visitors or JSON-LD
  priceConfirmationStatus: 'confirmed' | 'unconfirmed';
  availabilityStatus: 'available' | 'sold-out' | 'pre-order';
  isFeatured?: boolean;
  tags?: string[];
}

